/*Magnitude Analysis*/

--comparing measure values by categories
--Formula is : Agg(Measure) By (Dimension)

--Find total sales by country
select
country,
sum(sales_amount) as total_sales
from gold.fact_sales as s
left join gold.dim_customers as c
on s.customer_key=c.customer_key
group by country

--Find total customers by country
select
country,
count(customer_key) as total_customers
from gold.dim_customers
group by country
order by total_customers desc

--Find the total customer by gender
select 
gender,
count(customer_key) as total_customer
from gold.dim_customers
group by gender
order by total_customer desc

--find the total products by category
select 
category,
count(distinct (product_name)) as total_products
from gold.dim_products
group by category

--what is avg costs in each category?
select
category,
avg(cost) as avg_cost
from gold.dim_products
group by category
order by avg_cost desc

--What is total revenue generated for each category
select
p.category,
sum(s.sales_amount) as total_revenue
from gold.fact_sales as s
left join gold.dim_products as p
on s.product_key=p.product_key
group by category

--total revenue generated by each customer
select
c.customer_key,
c.first_name,
c.last_name,
sum(s.sales_amount) as total_revenue
from gold.fact_sales as s
left join gold.dim_customers as c
on s.customer_key=c.customer_key
group by c.customer_key,c.first_name,c.last_name
order by total_revenue desc

--What is distribution of sold items accross countries
select
country,
sum(quantity) as total_distribution
from gold.fact_sales as s
left join gold.dim_customers as c
on s.customer_key=c.customer_key
group by country